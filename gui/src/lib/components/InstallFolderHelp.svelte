<details class="folder-help">
  <summary>How to install or import cheats</summary>
  <p><strong>Install directly</strong> uses your emulator’s existing <code>load</code> folder. In the Android picker, open that emulator’s storage, select <code>load</code>, and confirm with <strong>Use this folder</strong>.</p>
  <p><strong>Prepare for import</strong> saves files for an emulator that imports cheats. Choose a writable folder on your device or SD card. EDC uses its <code>load</code> subfolder, creating it if needed. You can also choose <code>load</code> itself.</p>
  <p>For example, in Peanuts Native, open the game and choose <strong>Mods &amp; Cheats › Add › A folder</strong>. Select <code>load/&lt;title ID&gt;</code> for that game. Importing the whole folder can hit the importer’s file limit. When updating a cheat, remove the old copy in the emulator before importing again.</p>
</details>

